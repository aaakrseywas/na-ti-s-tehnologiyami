@app.context_processor
def inject_lessons():
    """
    Делает список уроков доступным во всех шаблонах
    под именем all_lessons. Нужен для меню в base.html.
    """
    return {'all_lessons': lessons}


@app.route('/')
def index():
    return render_template('index.html', lessons=lessons)


@app.route('/lesson1/1')
def lesson():
    return render_template('lesson1.html', slides=slides)

LESSON_ROUTES = {
    1: 'lesson1.html',
    2: 'lesson2.html',
}


@app.route('/lesson/<int:n>')
def lesson_by_num(n):
    """
    """
    template = LESSON_ROUTES.get(n, 'lesson1.html')
    return render_template(template)


